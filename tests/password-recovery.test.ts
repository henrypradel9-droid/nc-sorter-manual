import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

test("delegated account recovery enforces permissions, mandatory change, expiry and stale-session denial", async () => {
  const db = new PGlite();
  try {
    const ids = [1,2,3,4,5].map(n => `11000000-0000-4000-8000-${String(n).padStart(12,"0")}`);
    const [owner, delegate, regular, operator, removed] = ids;
    const oldSession = "21000000-0000-4000-8000-000000000001";
    const newSession = "21000000-0000-4000-8000-000000000002";
    await db.exec(`create role anon; create role authenticated; create role service_role;
      create schema auth; create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb,encrypted_password text);
      create table auth.sessions(id uuid primary key,user_id uuid,created_at timestamptz);
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      create function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb$$;
      grant usage on schema auth to authenticated; grant execute on function auth.uid(),auth.jwt() to authenticated;`);
    await db.exec(await readFile(new URL("../db/schema.sql", import.meta.url), "utf8"));
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [owner]);
    for (const [i,id] of ids.entries()) {
      await db.query("insert into auth.users(id,email,encrypted_password) values($1,$2,'original-hash')", [id,`person${i}@example.test`]);
      await db.query("insert into profiles(id,name,email,role,active,created_at) values($1,$2,$3,$4,true,$5)", [id,`Person ${i}`,`person${i}@example.test`,i<3?'ADMIN':'OPERADOR',`2026-10-0${i+1}T12:00Z`]);
    }
    for (const name of ["access-requests-dashboard", "primary-admin-user-deletion", "official-v2", "compact-menu-operator-read", "operator-dashboard", "operator-shared-dashboard", "account-admin-password-recovery"])
      await db.exec(await readFile(new URL(`../db/${name}.sql`, import.meta.url), "utf8"));
    const as = async (id: string, session = "", role = "authenticated") => {
      await db.exec("reset role");
      await db.query("select set_config('request.jwt.claim.sub',$1,false),set_config('request.jwt.claims',$2,false)", [id,JSON.stringify({sub:id,session_id:session,role})]);
      await db.exec(`set role ${role}`);
    };
    const caps = async () => (await db.query<{v:{can_delete:boolean;can_reset_password:boolean;protected_user_ids:string[]}}>("select user_admin_capabilities() v")).rows[0].v;
    const state = async () => (await db.query<{v:{required:boolean;session_valid:boolean}}>("select password_change_state() v")).rows[0].v;
    const role = async () => (await db.query<{v:string|null}>("select private.current_role() v")).rows[0].v;
    const begin = async (id: string, email: string) => (await db.query<{v:string}>("select begin_password_reset($1,$2) v",[id,email])).rows[0].v;
    await as(regular);
    assert.deepEqual(await caps(), {can_delete:false,can_reset_password:false,protected_user_ids:[]});
    await assert.rejects(db.query("select grant_account_admin($1)",[regular]),/owner required/);
    await assert.rejects(begin(operator,"person3@example.test"),/administrator required/);
    await assert.rejects(db.query("insert into private.account_admins(user_id) values($1)",[regular]),/permission denied/);
    await as(operator);
    await assert.rejects(caps(),/Administrator required/);
    await as(owner);
    await db.query("select grant_account_admin($1)",[delegate]);
    assert.deepEqual(new Set((await caps()).protected_user_ids),new Set([owner,delegate]));
    await as(delegate);
    assert.equal((await caps()).can_reset_password,true);
    await assert.rejects(db.query("select grant_account_admin($1)",[regular]),/owner required/);
    await assert.rejects(db.query("select delete_user_access($1,$2)",[owner,"person0@example.test"]),/protected/);
    await assert.rejects(db.query("update profiles set active=false where id=$1",[owner]),/protected/);
    await db.query("select delete_user_access($1,$2)",[removed,"person4@example.test"]);
    await assert.rejects(begin(removed,"person4@example.test"),/Active user required/);
    await assert.rejects(begin(delegate,"person1@example.test"),/administrator required/);
    await assert.rejects(begin(operator,"wrong@example.test"),/does not match/);
    await db.exec("reset role");
    await db.query("insert into auth.sessions values($1,$2,now()-interval '1 hour')",[oldSession,operator]);
    await as(delegate);
    const request = await begin(operator,"PERSON3@example.test");
    await assert.rejects(begin(operator,"person3@example.test"),/five minutes/);
    await assert.rejects(db.query("select finish_password_reset($1,$2)",[operator,request]),/permission denied/);
    await as(operator,oldSession);
    assert.equal(await role(),null);
    assert.equal((await state()).session_valid,false);
    await assert.rejects(db.query("select complete_password_change()"),/Valid session required/);
    await db.exec("reset role");
    await db.query("update auth.users set encrypted_password='temporary-hash' where id=$1",[operator]);
    await as("", "", "service_role");
    await db.query("select finish_password_reset($1,$2)",[operator,request]);
    await db.exec("reset role");
    await db.query("insert into auth.sessions values($1,$2,clock_timestamp()+interval '1 second')",[newSession,operator]);
    await as(operator,newSession);
    assert.deepEqual(await state(),{required:true,session_valid:true});
    assert.equal(await role(),null);
    await assert.rejects(db.query("select dashboard_v2('{}','day')"));
    await assert.rejects(db.query("select complete_password_change()"),/Change the temporary password first/);
    await assert.rejects(db.query("update private.password_resets set required=false"),/permission denied/);
    await db.exec("reset role");
    await db.query("update private.password_resets set expires_at=now()-interval '1 second' where user_id=$1",[operator]);
    await as(operator,newSession);
    assert.equal((await state()).session_valid,false);
    await db.exec("reset role");
    await db.query("update private.password_resets set expires_at=now()+interval '1 hour' where user_id=$1",[operator]);
    await db.query("update auth.users set encrypted_password='personal-hash' where id=$1",[operator]);
    await as(operator,newSession);
    await db.query("select complete_password_change()");
    assert.deepEqual(await state(),{required:false,session_valid:true});
    assert.equal(await role(),"OPERADOR");
    await as(operator,oldSession);
    assert.equal(await role(),null);
    assert.equal((await state()).session_valid,false);
    await as(owner);
    await assert.rejects(db.query("select delete_user_access($1,$2)",[delegate,"person1@example.test"]),/protected/);
    const audit = (await db.query<{action:string;new_data:unknown}>("select action,new_data from audit_logs where action in ('PASSWORD_CHANGED','PASSWORD_RESET_COMPLETED','PASSWORD_RESET_REQUESTED','ACCOUNT_ADMIN_GRANTED')")).rows;
    assert.equal(audit.length,4);
    assert(!JSON.stringify(audit).includes("hash"));
    await db.exec("reset role; set role anon");
    await assert.rejects(db.query("select password_change_state()"),/permission denied/);
    await assert.rejects(begin(operator,"person3@example.test"),/permission denied/);
  } finally { await db.close(); }
});
